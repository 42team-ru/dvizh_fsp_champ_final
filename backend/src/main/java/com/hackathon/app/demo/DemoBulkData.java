    /**
     * Площадка: indoor — зал, sports — какие виды спорта там реально проходят (футбол — на поле, хоккей — на льду,
     * плавание — в бассейне). Координаты — точка самой площадки по OpenStreetMap, на суше, а не центр парка или города.
     */
    record Venue(String name, String address, double lat, double lon, boolean indoor, Set<String> sports) {

        boolean fits(Template template) {
            return sports.contains(template.sport()) && (template.indoor() == null || indoor == template.indoor());
        }
    }

    /** Город: вес — доля пользователей и мероприятий; клубные футболки — что носят местные бобры. */
    record City(String name, ZoneId zone, int weight, List<Venue> venues, List<String> shirts) {

        boolean hosts(Template template) {
            return venues.stream().anyMatch(v -> v.fits(template));
        }
    }

