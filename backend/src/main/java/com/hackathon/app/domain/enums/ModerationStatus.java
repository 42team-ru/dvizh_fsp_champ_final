package com.hackathon.app.domain.enums;

/** Состояние проверки текста. */
public enum ModerationStatus {
	/** Ждёт проверки нейросетью. */
	PENDING,
	/** Проверено, нарушений нет. */
	CLEAN,
	/** Сомнительно: ждёт решения администратора. */
	FLAGGED,
	/** Явное нарушение в сообщении: скрыто автоматически, администратор может вернуть. */
	AUTO_HIDDEN,
	/** Администратор принял решение. */
	RESOLVED
}
