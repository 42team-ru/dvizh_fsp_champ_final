package com.hackathon.app.domain.enums;

/** Решение администратора по проверке. */
public enum ModerationDecision {
	/** Всё в порядке: флаг снят, автоскрытое сообщение возвращено. */
	APPROVED,
	/** Сообщение скрыто. */
	HIDDEN,
	/** Принята другая мера: текст профиля очищен, мероприятие снято, анкета возвращена. */
	ACTION_TAKEN
}
