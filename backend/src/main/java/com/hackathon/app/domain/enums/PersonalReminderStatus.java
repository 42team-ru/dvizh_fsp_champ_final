package com.hackathon.app.domain.enums;

/** Состояние личного напоминания «пора выходить». */
public enum PersonalReminderStatus {
	/** Ждёт своего времени. */
	SCHEDULED,
	/** Отправлено. */
	SENT,
	/** Отменено пользователем или потеряло смысл (занятие перенесли, отменили, участник вышел). */
	CANCELLED,
	/** Пользователь нажал «Не надо»: подсказку на это занятие не показываем. */
	DISMISSED
}
