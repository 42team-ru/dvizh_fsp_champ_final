package com.hackathon.app.domain.enums;

/** Признак, из которого складывается оценка рекомендации; каждый нормирован в [0, 1]. */
public enum RecommendationFeatureCode {
	/** Интерес к виду спорта: профиль, история с затуханием и похожие виды. */
	SPORT,
	/** Совпадение уровня мероприятия с моим. */
	LEVEL,
	/** Расстояние: гауссово ядро, половина оценки на радиусе поиска. */
	DISTANCE,
	/** Удобные день и время суток: предпочтения и привычки. */
	TIME,
	/** Знакомые участники: граф совместных встреч. */
	SOCIAL,
	/** Знакомый организатор или похожий на знакомого (совместная аудитория). */
	ORGANIZER,
	/** Надёжность организатора: сглаженное число проведённых встреч. */
	TRUST,
	/** Популярность: сколько уже записались. */
	POPULARITY,
	/** Кворум почти набран. */
	QUORUM,
	/** Близость начала. */
	URGENCY,
	/** Клуб: активность — число ближайших встреч. */
	ACTIVITY,
	/** Клуб: доля встреч, подходящих новичкам. */
	BEGINNER
}
