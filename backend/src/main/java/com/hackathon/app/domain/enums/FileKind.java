package com.hackathon.app.domain.enums;

/** Назначение загруженного файла: от него зависят допустимые форматы, лимиты и кто может скачать. */
public enum FileKind {
	/** Аватар пользователя. */
	AVATAR,
	/** Фото в личной галерее пользователя, отдельно от аватара. */
	USER_PHOTO,
	/** Логотип организации. */
	ORG_LOGO,
	/** Документ организации (устав, свидетельство и т.п.). */
	ORG_DOCUMENT,
	/** Фото в альбоме профиля с занятия, где человек был или которое организовал; папка — мероприятие. */
	ALBUM_PHOTO,
	/** Фото мероприятия; первое по порядку — обложка в ленте. */
	EVENT_PHOTO,
	/** Фото поста в блоге, загруженное автором. */
	BLOG_PHOTO,
	/** PNG-иллюстрация вида спорта, загруженная админом. */
	SPORT_IMAGE,
	/** Старое назначение сохранённых файлов; новые файлы этого типа больше не создаются. */
	@Deprecated
	PET_ITEM
}
