package com.hackathon.app.domain.enums;

/** Назначение загруженного файла: от него зависят допустимые форматы, лимиты и кто может скачать. */
public enum FileKind {
	/** Аватар пользователя. */
	AVATAR,
	/** Логотип организации. */
	ORG_LOGO,
	/** Документ организации (устав, свидетельство и т.п.). */
	ORG_DOCUMENT,
	/** Фото мероприятия; первое по порядку — обложка в ленте. */
	EVENT_PHOTO,
	/** Старое назначение сохранённых файлов; новые файлы этого типа больше не создаются. */
	@Deprecated
	PET_ITEM
}
