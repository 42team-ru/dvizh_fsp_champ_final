package com.hackathon.app.domain.enums;

/** Статус допуска организации. */
public enum OrganizationStatus {
	/** Заявка подана и ждёт решения администратора. */
	PENDING,
	/** Допущена: публичная страница и публикация мероприятий без модерации. */
	APPROVED,
	/** Отклонена с причиной; можно исправить анкету и подать снова. */
	REJECTED,
	/** Возвращена на доработку с причиной: не отказ, а просьба дополнить анкету; правка снова отправляет на проверку. */
	REVISION
}
