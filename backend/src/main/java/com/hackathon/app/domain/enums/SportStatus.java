package com.hackathon.app.domain.enums;

/** Состояние вида спорта в справочнике. */
public enum SportStatus {
	/** Из справочника или одобрен админом: доступен везде. */
	ACTIVE,
	/** Свой вид пользователя, который ещё не проверил админ: им уже можно пользоваться. */
	PENDING,
	/** Отключён админом: не предлагается в справочнике, новое мероприятие с ним создать нельзя. */
	HIDDEN,
	/** Объединён с другим видом (mergedIntoId): мероприятия и интересы уже перенесены. */
	MERGED
}
