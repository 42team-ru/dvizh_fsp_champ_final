package com.hackathon.app.domain.enums;

/** Откуда взялось занятие. */
public enum OccurrenceSource {
	/** Единственное занятие разового мероприятия: его время — startAt/endAt самого мероприятия. */
	SINGLE,
	/** Развёрнуто из правила расписания серии; пересчитывается при правке правил. */
	RULE,
	/** Разовая дата, добавленная организатором вне правил; правка правил её не трогает. */
	EXTRA
}
