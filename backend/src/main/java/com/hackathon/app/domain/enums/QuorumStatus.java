package com.hackathon.app.domain.enums;

/** Кворум занятия: «состоится, если наберём N». Считается на лету, не хранится. */
public enum QuorumStatus {
	/** Пока не набрали и организатор не подтвердил: занятие под вопросом. */
	GATHERING,
	/** Набрали N: занятие состоится. */
	REACHED,
	/** Организатор подтвердил, что занятие состоится (в том числе в меньшем составе); подтверждение не снимается. */
	CONFIRMED
}
