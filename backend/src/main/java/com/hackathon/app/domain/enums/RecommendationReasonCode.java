package com.hackathon.app.domain.enums;

/** Причина, по которой мероприятие или клуб попали в подборку; фронт может подобрать по коду иконку. */
public enum RecommendationReasonCode {
	/** Вид спорта из моих интересов или истории. */
	YOUR_SPORT,
	/** Вид спорта, похожий на мои (им занимаются те же люди). */
	RELATED_SPORT,
	/** Уровень мероприятия совпадает с моим. */
	LEVEL_FIT,
	/** Подходит новичкам: уровень «Любой» или «Новичок». */
	BEGINNER_FRIENDLY,
	/** Рядом с точкой отсчёта (дом или текущее место). */
	NEARBY,
	/** Онлайн: можно присоединиться откуда угодно. */
	ONLINE,
	/** День и время совпадают с моими предпочтениями или привычками. */
	GOOD_TIME,
	/** Записались люди, с которыми я уже занимался. */
	FRIENDS_GOING,
	/** Организатор, у которого я уже был (или к которому ходят те же люди). */
	KNOWN_ORGANIZER,
	/** Организатор с большим опытом проведённых встреч. */
	TRUSTED_ORGANIZER,
	/** Кворум почти набран: встреча состоится, если я приду. */
	NEEDS_PEOPLE,
	/** Много участников. */
	POPULAR,
	/** Скоро начнётся. */
	SOON,
	/** Попробовать новый для меня вид спорта. */
	NEW_SPORT,
	/** Организация месяца. */
	AWARDED,
	/** Клуб в моём городе. */
	SAME_CITY,
	/** У клуба много ближайших встреч. */
	ACTIVE
}
