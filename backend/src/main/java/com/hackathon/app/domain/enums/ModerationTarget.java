package com.hackathon.app.domain.enums;

/** Что проверяет модерация текста. */
public enum ModerationTarget {
	/** Сообщение в обсуждении мероприятия. */
	COMMENT,
	/** Тексты мероприятия: название, описание, требования, инвентарь, место, объявление. */
	EVENT,
	/** Профиль человека: имя, фамилия, «о себе». */
	USER_PROFILE,
	/** Анкета организации: название и описание. */
	ORGANIZATION
}
