package com.hackathon.app.domain.enums;

/**
 * Тип слота бобра: от него зависит, где значение лежит в образе (mood, activity или outfit).
 */
public enum PetSlotKind {
    /**
     * Настроение (выражение мордочки); всегда что-то выбрано, по умолчанию idle.
     */
    MOOD,
    /**
     * Инвентарь рядом с бобром; по умолчанию none.
     */
    ACTIVITY,
    /**
     * Часть одежды: может быть пустой. Новые слоты админ добавляет только этого типа.
     */
    OUTFIT
}
