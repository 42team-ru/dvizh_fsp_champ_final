-- Справочник видов спорта: новый вид = новая строка, а не изменение кода.
CREATE TABLE sports (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50)  NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);
